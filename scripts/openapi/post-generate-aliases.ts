import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// The single generated SDK has one class per domain tag (Base, Booking, ...).
// These aliases keep the controller-style names used across the app working.
const aliasesByClass: Record<string, string[]> = {
  Base: [
    'AuthController',
    'AdminCompanyController',
    'AdminCompanyUserController',
    'CompanyUserController',
    'CompanyUserContactController',
    'PublicCompanyController',
    'PublicUserController',
  ],
  Booking: [
    'AppointmentsController',
    'CompanyUserAppointmentController',
    'CompanyUserBookingController',
    'CompanyUserBookingProfileController',
    'CompanyUserScheduleController',
    'CompanyUserScheduleUnavailabilityController',
    'CompanyUserServiceGroupController',
    'DailyScheduleController',
    'PublicAppointmentSessionController',
    'ServiceController',
  ],
  Marketing: ['CompanyUserMarketingCampaignController', 'PublicUnsubscribeController'],
  Notification: ['CompanyUserInAppNotificationController'],
  Timesheet: ['AdminTimeSheetEntryController', 'CompanyUserTimesheetEntryController'],
};

const START = '// compat-aliases:start';
const END = '// compat-aliases:end';

const file = resolve(process.cwd(), 'app/api/generated/index.ts');
let source = readFileSync(file, 'utf8');

const classes = Object.keys(aliasesByClass);
const importLine = `import { ${classes.map((c) => `${c} as ${c}Sdk`).join(', ')} } from './sdk.gen';`;
const marker = '// This file is auto-generated by @hey-api/openapi-ts\n\n';

if (!source.includes(importLine)) {
  source = source.replace(marker, `${marker}${importLine}\n`);
}

const aliasLines = classes.flatMap((c) => aliasesByClass[c].map((name) => `export const ${name} = ${c}Sdk;`));
const block = `${START}\n${aliasLines.join('\n')}\n${END}`;

if (source.includes(START) && source.includes(END)) {
  const end = source.indexOf(END) + END.length;
  source = `${source.slice(0, source.indexOf(START))}${block}${source.slice(end)}`;
} else {
  const lines = source.split('\n');
  const exportIdx = lines.findIndex((l) => l.startsWith('export {') && l.includes("from './sdk.gen';"));
  if (exportIdx === -1) {
    throw new Error('Could not find the sdk.gen export line in generated index.ts');
  }
  lines.splice(exportIdx + 1, 0, block);
  source = lines.join('\n');
}

writeFileSync(file, source, 'utf8');
console.log('Applied generated API controller compatibility aliases.');
